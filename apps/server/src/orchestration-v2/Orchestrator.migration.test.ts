import { assert, it } from "@effect/vitest";

import { shouldPrepareLegacyImportHandoff } from "./Orchestrator.ts";

it("reissues imported context until a V2 run completes", () => {
  assert.isTrue(
    shouldPrepareLegacyImportHandoff({
      historyOrigin: "v1_import",
      hasCompletedRun: false,
      resumesNativeThread: false,
    }),
  );
  assert.isFalse(
    shouldPrepareLegacyImportHandoff({
      historyOrigin: "v1_import",
      hasCompletedRun: true,
      resumesNativeThread: false,
    }),
  );
  assert.isFalse(
    shouldPrepareLegacyImportHandoff({
      historyOrigin: undefined,
      hasCompletedRun: false,
      resumesNativeThread: false,
    }),
  );
});

it("sends no imported context to an agent session that resumes its own history", () => {
  assert.isFalse(
    shouldPrepareLegacyImportHandoff({
      historyOrigin: "v1_import",
      hasCompletedRun: false,
      resumesNativeThread: true,
    }),
  );
});
